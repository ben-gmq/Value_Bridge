"""Print the shadow tables as literal Alembic DDL (slice8_schema §9 [Q-4]).

Run once to write migration 0048's TABLES block; the output is committed and never regenerated on replay,
so a fresh database next year builds the shadows as they were at 0048. After 0048, a migration that adds a
column to a shadowed live table adds the shadow column itself; tests/test_baseline.py compares the
database with services/baseline_shadow.py.

    ./venv/bin/python -m scripts.print_shadow_ddl
"""
from sqlalchemy import CHAR, BigInteger, Boolean, Integer, Numeric, SmallInteger, String, Text


def render_type(t) -> str:
    if isinstance(t, CHAR):
        return f"sa.CHAR({t.length})"
    if isinstance(t, String) and not isinstance(t, Text):
        return f"sa.String({t.length})"
    if isinstance(t, Text):
        return "sa.Text()"
    if isinstance(t, Numeric):
        return f"sa.Numeric({t.precision}, {t.scale})"
    for cls in (BigInteger, SmallInteger, Integer, Boolean):    # subclasses first
        if isinstance(t, cls):
            return f"sa.{cls.__name__}()"
    raise TypeError(f"no rendering for {t!r}")


def main() -> None:
    from models import SHADOW_TABLES
    print("TABLES = {   # generated by scripts/print_shadow_ddl.py — do not edit by hand")
    for live, shadow in SHADOW_TABLES.items():
        (pk,) = [fk for fk in shadow.foreign_key_constraints if fk.name.endswith("_source")]
        target = pk.elements[0].target_fullname
        cols = [c for c in shadow.columns if c.name not in (f"{shadow.name}_id", "baseline_id", "source_id",
                                                              "content_hash")]
        print(f'    "{live}": ("{target}", [')
        for c in cols:
            print(f'        ("{c.name}", {render_type(c.type)}),')
        print("    ]),")
    print("}")


if __name__ == "__main__":
    main()
